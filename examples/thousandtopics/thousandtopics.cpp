class G {
public:
  virtual ~G() = default;
  virtual void t(bool& cont, uint32_t& n) {
    static_cast<void>(cont); static_cast<void>(n);
  }
};

template<typename T>
class z : public G {
public:
  z(dds::domain::DomainParticipant& dp, const std::string& tn, bool mkrd, bool mkwr)
  {
    tn_ = tn;
    dds::topic::Topic<T> topic1 =
      dds::topic::Topic<T>(dp, tn_.c_str());
    if (mkrd) {
      dds::sub::Subscriber subscriber1 = dds::sub::Subscriber(dp);
      auto qos = subscriber1->default_datareader_qos();
      qos << dds::core::policy::History::KeepLast(10);
      rd_ = dds::sub::DataReader<T>(subscriber1, topic1, qos);
    }
    if (mkwr) {
      dds::pub::Publisher publisher1 = dds::pub::Publisher(dp);
      auto qos = publisher1->default_datawriter_qos();
      qos << dds::core::policy::History::KeepLast(10);
      wr_ = dds::pub::DataWriter<T>(publisher1, topic1, qos);
    }
  }

  void t(bool& cont, uint32_t& n)
  {
    if (rd_ != dds::core::null) {
      dds::sub::LoanedSamples<T> samples = rd_->take();
      if (samples.length() > 0) {
        for (auto& sample : samples) {
          if (sample.info().valid()) {
            ++n;
          } else { // stop on unregister/dispose for convenience
            cont = false;
          }
        }
      }
    }
    if (wr_ != dds::core::null) {
      wr_ << T{k_++};
    }
  }

private:
  std::string tn_;
  uint32_t k_{0};
  dds::sub::DataReader<T> rd_ = dds::core::null;
  dds::pub::DataWriter<T> wr_ = dds::core::null;
};

